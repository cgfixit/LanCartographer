//go:build ignore

// gen.go regenerates oui_data.go from data.csv. Run via:
//
//	go generate ./internal/oui/
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

const (
	csvPath = "data.csv"
	outPath = "oui_data.go"
)

func main() {
	f, err := os.Open(csvPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "open", csvPath, err)
		os.Exit(1)
	}
	defer f.Close()

	vendors := map[string]string{}
	sc := bufio.NewScanner(f)
	line := 0
	for sc.Scan() {
		line++
		row := strings.TrimSpace(sc.Text())
		if row == "" || strings.HasPrefix(row, "#") {
			continue
		}
		prefix, vendor, ok := strings.Cut(row, ",")
		if !ok || len(prefix) != 6 || strings.ToUpper(prefix) != prefix || strings.TrimSpace(vendor) == "" {
			fmt.Fprintf(os.Stderr, "%s:%d: malformed row %q (want HEXPREFIX,Vendor, prefix = 6 uppercase hex chars)\n", csvPath, line, row)
			os.Exit(1)
		}
		if !isHex6(prefix) {
			fmt.Fprintf(os.Stderr, "%s:%d: prefix %q is not hex\n", csvPath, line, prefix)
			os.Exit(1)
		}
		if _, dup := vendors[prefix]; dup {
			fmt.Fprintf(os.Stderr, "%s:%d: duplicate prefix %q\n", csvPath, line, prefix)
			os.Exit(1)
		}
		vendors[prefix] = strings.TrimSpace(vendor)
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, "read", csvPath, err)
		os.Exit(1)
	}

	keys := make([]string, 0, len(vendors))
	for k := range vendors {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen.go from data.csv; DO NOT EDIT.\n\n")
	buf.WriteString("package oui\n\n")
	buf.WriteString("// vendorByPrefix maps an uppercase 6-hex-char MAC prefix (first 3 bytes,\n// no separators) to the vendor name from data.csv.\n")
	buf.WriteString("var vendorByPrefix = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&buf, "\t%q: %q,\n", k, vendors[k])
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "gofmt generated source:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write", outPath, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s with %d prefixes\n", outPath, len(vendors))
}

func isHex6(s string) bool {
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !(c >= '0' && c <= '9' || c >= 'A' && c <= 'F') {
			return false
		}
	}
	return len(s) == 6
}
